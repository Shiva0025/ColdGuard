import { chromium } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5173/');
await p.getByLabel('Username').fill('operator');
await p.getByLabel('Password').fill('coldguard-demo');
await p.getByRole('button', { name: 'Sign in' }).click();
await p.waitForTimeout(1000);
await p.goto('http://localhost:5173/device/DC-S03');
await p.waitForTimeout(3000);
console.log('phase before:', await p.getByTestId('stream-phase').textContent());
const box = await p.locator('.u-over').first().boundingBox();
await p.mouse.move(box.x + box.width * 0.55, box.y + 100);
await p.mouse.down();
await p.mouse.move(box.x + box.width * 0.8, box.y + 100, { steps: 8 });
await p.mouse.up();
await p.waitForTimeout(2500);
console.log('phase after zoom:', await p.getByTestId('stream-phase').textContent());
await p.screenshot({ path: out + '-zoom.png' });
await p.getByRole('button', { name: 'Resume live' }).click();
await p.waitForTimeout(1500);
console.log('phase after resume:', await p.getByTestId('stream-phase').textContent());
await p.screenshot({ path: out + '-live.png' });
console.log('errors', errs);
await b.close();
