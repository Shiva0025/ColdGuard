// Scripted check of the break-the-network story on one truck (needs `npm run dev`).
import { chromium } from '@playwright/test';
const out = process.argv[2] ?? 'network';
const DEV = process.argv[3] ?? 'DC-S05';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1300 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:5173/');
await p.getByLabel('Username').fill('operator');
await p.getByLabel('Password').fill('coldguard-demo');
await p.getByRole('button', { name: 'Sign in' }).click();
await p.waitForTimeout(1000);
const tok = await p.evaluate(() => sessionStorage.getItem('coldguard.token'));
const post = (path, body) => p.evaluate(([path, body, tok]) => fetch('/api' + path, { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer ' + tok }, body: JSON.stringify(body) }).then((r) => r.status), [path, body, tok]);
console.log('door open', await post('/sim/fault', { kind: 'door_open', deviceId: DEV }));
await p.goto(`http://localhost:5173/device/${DEV}`);
await p.waitForTimeout(3000);
await p.getByRole('button', { name: 'Cut signal' }).click();
await p.waitForTimeout(2500);
await p.getByRole('button', { name: /Close refrigerated compartment/ }).first().click();
await p.waitForTimeout(20000);
await p.screenshot({ path: `${out}-offline.png`, fullPage: true });
const net = p.getByRole('region', { name: 'Break the network' });
console.log('offline panel:', (await net.innerText()).replace(/\n/g, ' | '));
await p.getByRole('button', { name: 'Restore signal' }).click();
await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}-back.png`, fullPage: true });
console.log('after reconnect:', (await net.innerText()).replace(/\n/g, ' | '));
console.log('stream:', await p.getByTestId('stream-phase').innerText());
console.log('errors', errs);
await b.close();
