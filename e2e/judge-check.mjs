// Scripted check: operator invites, a phone-sized browser joins and drives (needs `npm run dev`).
import { chromium, devices } from '@playwright/test';
const out = process.argv[2] ?? 'judge';
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', headless: true });
const opCtx = await b.newContext({ viewport: { width: 1440, height: 1100 } });
const op = await opCtx.newPage();
const errs = [];
op.on('pageerror', (e) => errs.push('op: ' + e.message));
await op.goto('http://localhost:5173/');
await op.getByLabel('Username').fill('operator');
await op.getByLabel('Password').fill('coldguard-demo');
await op.getByRole('button', { name: 'Sign in' }).click();
await op.waitForTimeout(800);
await op.goto('http://localhost:5173/control');
await op.getByRole('button', { name: /Create invite|New code/ }).click();
await op.waitForTimeout(1500);
const code = (await op.locator('text=/^code /').first().innerText()).match(/code (\w+)/)[1];
console.log('invite code', code);

const phCtx = await b.newContext({ ...devices['Pixel 7'] , hasTouch: true });
const ph = await phCtx.newPage();
ph.on('pageerror', (e) => errs.push('phone: ' + e.message));
await ph.goto(`http://localhost:5173/join/${code}`);
await ph.getByLabel('Your first name').fill('Priya');
await ph.getByRole('button', { name: 'Start driving' }).click();
await ph.waitForTimeout(4000);
await ph.getByRole('button', { name: 'Open door' }).click();
await ph.waitForTimeout(3000);
await ph.screenshot({ path: `${out}-phone1.png` });
await ph.getByRole('button', { name: 'Drive into tunnel' }).click();
await ph.waitForTimeout(1000);
const dev = (await ph.locator('header').innerText()).match(/GT-\d+/)[0];
console.log('phone drives', dev);
// Operator sends "close door" while the phone is in the tunnel.
const tok = await op.evaluate(() => sessionStorage.getItem('coldguard.token'));
const st = await op.evaluate(([dev, tok]) => fetch(`/api/devices/${dev}/commands`, { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'Bearer ' + tok }, body: JSON.stringify({ kind: 'close_door' }) }).then((r) => r.status), [dev, tok]);
console.log('command status', st);
await ph.waitForTimeout(8000);
await ph.screenshot({ path: `${out}-phone-tunnel.png` });
await ph.getByRole('button', { name: 'Exit tunnel' }).click();
await ph.waitForTimeout(5000);
await ph.screenshot({ path: `${out}-phone2.png` });
await op.waitForTimeout(1500);
await op.screenshot({ path: `${out}-control.png` });
const cmds = await op.evaluate(([dev, tok]) => fetch(`/api/devices/${dev}/commands`, { headers: { authorization: 'Bearer ' + tok } }).then((r) => r.json()), [dev, tok]);
console.log('command lifecycle:', cmds.commands[0].timeline.map((t) => t.state).join(' → '), '| queuedOffline', cmds.commands[0].queuedOffline);
console.log('phone text:', (await ph.locator('section[aria-label="Upload statistics"]').innerText()).replace(/\n/g, ' '));
console.log('errors', errs);
await b.close();
